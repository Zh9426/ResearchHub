export function zhError(value:string):string {
  const text=value.replace(/^Value error, /,'');
  if(errors[text])return errors[text];
  if(text.startsWith('String should have at least'))return '输入内容过短，请检查长度。';
  if(text.startsWith('String should have at most'))return '输入内容过长，请缩短内容。';
  if(text.startsWith('Input should be'))return '输入格式或选项不符合要求。';
  return text;
}
