export function zh(value:unknown):string {
  const text=String(value??'unknown');
  if(labels[text])return labels[text];
  const action=/^(create|update|delete)_(.+)$/.exec(text);
  if(action)return `${labels[action[1]]}${zh(action[2])}`;
  return text;
}
